package com.jizhangbao.core.domain

import java.time.LocalDate

/**
 * 工作日历的**只读端口**（`REQ-012`）：回答"这一天是什么日子"。
 *
 * ## 为什么端口住内核、实现住 Calendar
 *
 * 消费方是 Payroll、实现在 `feature:calendar`，而 `R2` 不许 feature 之间互相依赖。
 * 于是走 `ADR-0008` 已立的那条通路：**读通路住内核、实现住上下文、装配在 `:app`** ——
 * 与 `LedgerTotalsReader` 完全同构。`ADR-0011` 决策 4 记了这次裁决。
 *
 * ## 为什么没有"写"的方法
 *
 * 日期类型由**国务院发布的节假日与调休安排**决定，是外部事实。
 * 用户能"覆盖单日"这件事在**数据层**支持（覆盖表优先），但不是一个领域操作 ——
 * 把"今天是工作日吗"变成可写状态，会让工资的口径不再可解释（`ADR-0011` 决策 1 的否决方案 c）。
 *
 * ## 为什么是同步的
 *
 * 本地数据、纯查询（`Conformist`）。把"今天是工作日吗"变成异步问题，
 * 是把最简单的问题复杂化（`ADR-0011` 决策 5）。
 */
interface WorkCalendar {

    /**
     * 判定某一天。
     *
     * **没有"判定一段时间"的重载**（初稿有一个，落地时删了）：
     * 调用方要一个月就自己循环 —— `dates.forEach { typeOf(it) }` 里**没有任何逻辑**，
     * 每一天各自解析自己的年份；而一个"区间"重载反而要回答"用谁的时区把瞬间变成日期"，
     * 那是调用方才知道的事。**加一个只会增加接口面积，不会减少重复。**
     */
    fun typeOf(date: LocalDate): DayTypeResult
}
